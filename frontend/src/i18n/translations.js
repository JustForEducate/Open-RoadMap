/** @param {string} [browserLang] */
export function detectDefaultLocale(browserLang) {
  if (typeof browserLang !== 'string') return 'en';
  const low = browserLang.toLowerCase();
  if (low.startsWith('ru')) return 'ru';
  return 'en';
}
